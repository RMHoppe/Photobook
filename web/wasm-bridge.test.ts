// ---------------------------------------------------------------------------
// computeImageCover (free function wrapper)
// ---------------------------------------------------------------------------

describe('computeImageCover', () => {
  it('returns a parsed ImageCoverResult with the expected fields', () => {
    const result = computeImageCover(200, 150, 400, 300, 0.5, 0.5, 1.0, 0.0);
    expect(result).not.toBeNull();
    expect(result!.sw).toBe(200);
    expect(result!.sh).toBe(150);
    expect(result!.overflow_x).toBe(50);
    expect(result!.pan_off_x).toBe(25);
  });

  it('returns null when the WASM function returns the JSON string "null"', () => {
    computeImageCoverMock.mockReturnValueOnce('null');
    const result = computeImageCover(0, 0, 100, 100, 0.5, 0.5, 1.0, 0.0);
    expect(result).toBeNull();
  });

  it('forwards all eight arguments to the underlying WASM function', () => {
    computeImageCoverMock.mockClear();
    computeImageCover(100, 200, 300, 400, 0.1, 0.9, 1.5, 45.0);
    expect(computeImageCoverMock).toHaveBeenCalledWith(100, 200, 300, 400, 0.1, 0.9, 1.5, 45.0);
  });
});

// ---------------------------------------------------------------------------
// getResolvedSpreadDelta
// ---------------------------------------------------------------------------

describe('getResolvedSpreadDelta', () => {
  it('returns a SpreadDelta with null fields when nothing changed', () => {
    const delta = getResolvedSpreadDelta(makeEditor(), 1000, 500);
    expect(delta.full).toBeNull();
    expect(delta.updated_frames).toBeNull();
  });

  it('parses a full resolved spread when structure is dirty', () => {
    const fullSpread = {
      frames: [{ id: 1, rect: { x: 0, y: 0, w: 1000, h: 500 } }],
      dividers: [],
      twin_handles: [],
    };
    const editor = makeEditor({
      get_resolved_spread_delta: () => JSON.stringify({
        full: fullSpread,
        updated_frames: null,
        removed_frame_ids: null,
      }),
    });
    const delta = getResolvedSpreadDelta(editor, 1000, 500);
    expect(delta.full).not.toBeNull();
    expect(delta.full!.frames.length).toBe(1);
    expect(delta.full!.frames[0].id).toBe(1);
  });
});
