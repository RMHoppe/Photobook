describe('getUsedImageIds', () => {
  it('returns an empty Set when no images are placed', () => {
    const set = getUsedImageIds(makeEditor());
    expect(set instanceof Set).toBe(true);
    expect(set.size).toBe(0);
  });

  it('returns a Set of the placed image IDs', () => {
    const editor = makeEditor({
      get_used_image_ids: () => JSON.stringify(['img-1.jpg', 'img-2.png']),
    });
    const set = getUsedImageIds(editor);
    expect(set.size).toBe(2);
    expect(set.has('img-1.jpg')).toBe(true);
    expect(set.has('img-2.png')).toBe(true);
  });
});

